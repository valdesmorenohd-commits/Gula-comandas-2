import assert from 'node:assert/strict';
import {canPerform,PERMISSIONS,ROLE_DEFAULTS,simulateRole} from '../src/access-policy.mjs';
const user='uid-a',business='gula';
const allow=(roleId,permission,extra={})=>canPerform({authUid:user,businessId:business,membership:{uid:user,businessId:business,active:true,roleId,...extra},permission});
assert.equal(PERMISSIONS.length,15);
assert.equal(ROLE_DEFAULTS.principal_admin.length,PERMISSIONS.length);
assert.equal(allow('principal_admin','users.manage'),true);
assert.equal(allow('personal','orders.create'),true);
assert.equal(allow('personal','users.manage'),false);
assert.equal(allow('consulta','orders.read'),true);
assert.equal(allow('consulta','payments.record'),false);
assert.equal(allow('consulta','orders.create',{grants:['orders.create']}),true);
assert.equal(allow('consulta','users.manage',{grants:['users.manage']}),false);
assert.equal(allow('principal_admin','cash.close',{denies:['cash.close']}),false);
assert.equal(allow('principal_admin','orders.read',{active:false}),false);
assert.equal(allow('principal_admin','orders.read',{businessId:'otra-empresa'}),false);
assert.equal(allow('principal_admin','orders.read',{uid:'otro-uid'}),false);
assert.equal(allow('principal_admin','unlisted.permission'),false);
assert.equal(allow('admin','orders.create'),false);
assert.equal(canPerform(),false);
assert.equal(simulateRole('consulta').find(x=>x.key==='payments.record').allowed,false);
console.log('Gula 2.0: 14 pruebas de matriz de roles y denegación por defecto superadas.');
